#!/usr/bin/env python3
"""Download independent CC0 PBR plants and public-domain calendar photos.

There are NO original Pinewood 3D models generated by this script. The three
plant GLBs are exact original published binaries. Calendar cards are honest
photo-derived 2D wall props, with real source photographic paper and accurate
1997 grids rather than claiming third-party modeled calendar geometry.
"""
import calendar,hashlib,json,math,random
from io import BytesIO
from pathlib import Path
from urllib.request import Request,urlopen
from PIL import Image,ImageDraw,ImageFont,ImageEnhance,ImageFilter
ROOT=Path("assets/vendor/builder/mood-v101")
for sub in ["models","calendar-source","calendars"]:(ROOT/sub).mkdir(parents=True,exist_ok=True)
UA={'User-Agent':'PinewoodMallPublisherSourceArchive/101 (educational creator attribution)'}
def get(u,limit=15_000_000):
 with urlopen(Request(u,headers=UA),timeout=75) as r:b=r.read(limit+1);resolved=r.geturl()
 if not 100<len(b)<=limit:raise RuntimeError("Download failed or oversized "+u)
 return b,resolved
def pin(p,b):
 p.write_bytes(b)
 return dict(bytes=len(b),sha256=hashlib.sha256(b).hexdigest())
models=[
 ('haworthia','Potted Zebra Haworthia (Realistic)','potted-zebra-haworthia-4acc845e','James Ray Cock','https://polyhaven.com/a/potted_plant_04',.27,.30),
 ('heartleaf','Terracotta Heartleaf (Realistic)','potted-plant-in-a-terracotta-pot-fd420e6b','Rico Cilliers','https://polyhaven.com/a/potted_plant_02',.53,.52),
 ('snake-plant','Ceramic Desk Snake Plant','sword-plant-plant-accessory-8a944229','Innerscene','https://www.innerscene.com/tools/library/3d-parts/sword-plant-plant-accessory-8a944229',.49,.30)
]
outModels=[]
for slug,label,sourceSlug,author,origPage,height,radius in models:
 src='https://www.innerscene.com/tools/library/3d-parts/'+sourceSlug
 url='https://www.innerscene.com/api/library/'+sourceSlug+'/download'
 data,resolved=get(url)
 if data[:4]!=b'glTF' or int.from_bytes(data[4:8],'little')!=2 or int.from_bytes(data[8:12],'little')!=len(data):raise RuntimeError("Not original source GLB "+slug)
 n=int.from_bytes(data[12:16],'little');j=json.loads(data[20:20+n])
 if len(j.get('meshes',[]))<1 or len(j.get('images',[]))<1:raise RuntimeError("Missing original source mesh or PBR maps")
 p=ROOT/"models"/(slug+".glb");info=pin(p,data)
 outModels.append(dict(id="mood-v101-"+slug,label=label,category="Realistic Desk Plants",kind="model",path=str(p),
  condition="weathered",materialStyle="image-mapped",license="CC0-1.0",originalAuthor=author,
  originalSource=origPage,mirrorPage=src,downloadUrl=url,resolvedDownloadUrl=resolved,
  sourceSHA256=info['sha256'],sourceBytes=info['bytes'],sourceMeshCount=len(j['meshes']),
  sourceImageCount=len(j['images']),sourceMaterials=len(j.get('materials',[])),
  targetHeight=height,radius=radius,skipMaterialEnhancement=True,**info))
 print('PLANT',slug,info['bytes'],info['sha256'],flush=True)
# A fourth entry is an aged transformation of the same independently sourced
# real PBR haworthia, not a new independently modeled or downloaded source.
withering={**outModels[0], 'id':'mood-v101-browning-haworthia','label':'Neglected Browning Haworthia',
 'plantCondition':'browning','variationOf':'mood-v101-haworthia'}
outModels.append(withering)

photos=[
 ('public-domain-wall-calendar','https://commons.wikimedia.org/wiki/File:WallCalendar.jpg',
  'https://commons.wikimedia.org/wiki/Special:FilePath/WallCalendar.jpg','Claudio Elias','Public-domain (PD-self)'),
 ('cc0-wooden-wall-calendar','https://commons.wikimedia.org/wiki/File:Manual_scrollable_wooden_wall_calendar.jpg',
  'https://commons.wikimedia.org/wiki/Special:FilePath/Manual_scrollable_wooden_wall_calendar.jpg','Amitbalani','CC0-1.0')
]
sourceDocs=[];photosLoaded={}
for slug,page,url,author,license in photos:
 b,resolved=get(url,8_000_000);img=Image.open(BytesIO(b)).convert('RGB')
 if min(img.size)<600:raise RuntimeError('Calendar source too small: '+slug)
 p=ROOT/"calendar-source"/(slug+".jpg");info=pin(p,b)
 sourceDocs.append(dict(id=slug,sourcePage=page,downloadUrl=url,resolvedDownloadUrl=resolved,
   author=author,license=license,sourcePath=str(p),width=img.width,height=img.height,**info))
 photosLoaded[slug]=img
 print('CALENDAR_SOURCE',slug,img.size,info['sha256'],flush=True)
try:
 font_regular='/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf'
 font_bold='/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf'
 def font(sz,bold=False):return ImageFont.truetype(font_bold if bold else font_regular,sz)
except:font=lambda sz,bold=False:ImageFont.load_default()
def paper(xseed,large,photoSlug):
 random.seed(xseed)
 im=Image.new('RGBA',(1024,1024),(0,0,0,0))
 # Source photo colors are used as the real material/paper underneath the
 # legible, owner-required era-appropriate dated month grids.
 source=photosLoaded[photoSlug]
 src=source.resize((1024,1024),Image.Resampling.LANCZOS).convert('RGBA')
 # Keep original photographic grain/variation at low intensity.
 base=Image.new('RGBA',(1024,1024),(221,209,187,255))
 base=Image.blend(base,src,.21 if large else .31)
 im.alpha_composite(base)
 shade=Image.new('RGBA',im.size,(255,255,255,0))
 d=ImageDraw.Draw(shade)
 for j in range(7000):
  x=random.randrange(1024);y=random.randrange(1024)
  a=random.randrange(2,10)
  d.point((x,y),fill=(57,48,37,a))
 shade=shade.filter(ImageFilter.GaussianBlur(.45));im=Image.alpha_composite(im,shade)
 return im
def monthgrid(d,year,month,rect,ink,heading=True):
 x,y,w,h=rect
 if heading:
  d.text((x+10,y+5),calendar.month_name[month].upper()+' '+str(year),
   font=font(max(17,int(w/14)),True),fill=ink)
  y+=int(h*.18);h=int(h*.80)
 d.rectangle((x,y,x+w,y+h),outline=ink,width=3)
 weekdays='S M T W T F S'.split()
 cw=w/7
 for i,n in enumerate(weekdays):d.text((int(x+i*cw+cw*.25),y+4),n,font=font(max(12,int(cw*.27)),True),fill=ink)
 for row,week in enumerate(calendar.Calendar(firstweekday=6).monthdayscalendar(year,month)):
  for i,n in enumerate(week):
   if n:d.text((int(x+i*cw+cw*.24),int(y+(row+1)*h/7+4)),str(n),
     font=font(max(11,int(cw*.26))),fill=ink)
 for i in range(1,7):d.line((x,y+i*h/7,x+w,y+i*h/7),fill=(107,92,78,97),width=1)
 for i in range(1,7):d.line((x+i*cw,y,x+i*cw,y+h),fill=(107,92,78,97),width=1)
variants=[
 ('facilities-year-planner','Large 1997 Facilities Annual Planner',1.62,1.04,1,'public-domain-wall-calendar','commercial'),
 ('service-shift-calendar','Large 1997 Service Scheduling Calendar',1.35,.96,2,'public-domain-wall-calendar','commercial'),
 ('family-month-calendar','1997 Personal Kitchen Calendar',.56,.77,3,'cc0-wooden-wall-calendar','personal'),
 ('small-desk-wall-calendar','1997 Personal Wall Calendar',.46,.62,4,'cc0-wooden-wall-calendar','personal')
]
items=[]
for slug,label,width,height,seed,photoSlug,style in variants:
 art=paper(seed,style=='commercial',photoSlug);d=ImageDraw.Draw(art,'RGBA')
 ink=(48,43,37,255)
 if slug=='facilities-year-planner':
  d.rectangle((22,26,1002,128),fill=(59,75,65,245))
  d.text((50,47),'FACILITIES • 1997',font=font(53,True),fill=(239,235,222,255))
  for i in range(12):monthgrid(d,1997,i+1,(28+(i%4)*247,160+(i//4)*278,231,256),ink,True)
 elif slug=='service-shift-calendar':
  d.rectangle((24,25,1000,139),fill=(89,74,54,244))
  d.text((51,50),'SERVICE / MAINTENANCE   1997',font=font(36,True),fill=(246,236,215,255))
  for i in range(6):monthgrid(d,1997,i+1,(40+(i%2)*498,168+(i//2)*274,451,248),ink,True)
 elif slug=='family-month-calendar':
  # Respect photographic origin, leave its visible image grain as a soft top
  # picture instead of pretending this is an existing scanned 1997 print.
  src=photosLoaded[photoSlug];im=src.resize((942,458),Image.Resampling.LANCZOS).convert('RGBA')
  art.alpha_composite(im,(41,41))
  d.rectangle((40,502,984,983),fill=(224,211,185,246))
  monthgrid(d,1997,10,(57,524,906,433),ink,True)
  d.rectangle((40,41,983,497),outline=(92,81,68,255),width=5)
 else:
  src=photosLoaded[photoSlug];im=src.resize((930,420),Image.Resampling.LANCZOS).convert('RGBA')
  art.alpha_composite(im,(48,35))
  d.rectangle((40,476,984,982),fill=(231,222,199,239))
  monthgrid(d,1997,11,(65,493,891,467),ink,True)
  d.rectangle((47,34,981,464),outline=(87,70,62,255),width=4)
 # Never stamp artificially strong highlights: all calendar pixels are lit by
 # physical StandardMaterial later. Physically curled edges come from geometry.
 aging=ImageEnhance.Contrast(art).enhance(.93)
 out=BytesIO();aging.save(out,'PNG',optimize=True)
 p=ROOT/'calendars'/(slug+'.png');info=pin(p,out.getvalue())
 items.append(dict(id="mood-v101-calendar-"+slug,label=label,category="Wall Calendars & Planners",
  surface="wall",kind="surface-decal",condition="weathered",materialStyle="image-mapped",
  license="Source-derived PD/CC0",originalAuthor=sourceDocs[0 if photoSlug=='public-domain-wall-calendar' else 1]['author'],
  originalSource=sourceDocs[0 if photoSlug=='public-domain-wall-calendar' else 1]['sourcePage'],
  sourceId=photoSlug,derivation="Public-domain/CC0 original calendar photograph as material substrate; accurate 1997 printed month grid and period-styled frame newly composited. Not an external 3D calendar model.",
  path=str(p),thumb=str(p),width=width,height=height,opacity=.93,calendarStyle=style,year=1997,**info))
 print('CALENDAR',slug,info['bytes'],info['sha256'],flush=True)
manifest=dict(version=101,plants=outModels,calendars=items,sources=sourceDocs,
 notes="All plant GLBs are exact unmodified CC0 source files, one withering material variant reuses original geometry. Calendar assets are authored 2D wall calendar designs composited from PD/CC0 photographs, with accurate year 1997 typography. No claim to externally modeled 3D calendar geometry.")
(ROOT/'manifest-v101.json').write_text(json.dumps(manifest,indent=2)+'\n')
print('DONE',len(outModels),len(items),flush=True)
